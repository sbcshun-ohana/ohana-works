-- 版メタ(マスター全体の版。初版=1・公開)
create table development_master_versions (
  id uuid primary key default gen_random_uuid(),
  version int not null unique,
  status text not null default 'draft' check (status in ('draft', 'published', 'archived')),
  note text,
  published_by uuid references employees(id),
  published_at timestamptz,
  created_at timestamptz not null default now()
);
alter table development_master_versions enable row level security;

-- 発達項目マスター(stable識別。現在の内容)
create table development_item_masters (
  id uuid primary key default gen_random_uuid(),
  age_band_code text not null check (age_band_code in ('M00_05','M06_14','M15_23','AGE_2','AGE_3','AGE_4','AGE_5')),
  domain_code text not null check (domain_code in ('health','relations','environment','language','expression')),
  excel_domain text not null,
  item_name text not null,
  observation_point text,
  display_order int not null default 0,
  is_active boolean not null default true,
  source_ref int unique,
  current_version int not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index idx_dev_item_masters_band on development_item_masters(age_band_code, display_order) where is_active;
create trigger trg_dev_item_masters_updated_at before update on development_item_masters
  for each row execute function set_updated_at();
comment on table development_item_masters is '発達項目マスター(237・90項目)。全社共通・stable id。内容変更はversionsへスナップショット。';
alter table development_item_masters enable row level security;

-- 項目内容の版スナップショット(変更履歴・達成はこれを凍結参照)
create table development_item_master_versions (
  id uuid primary key default gen_random_uuid(),
  item_id uuid not null references development_item_masters(id) on delete cascade,
  version int not null,
  age_band_code text not null,
  domain_code text not null,
  item_name text not null,
  observation_point text,
  display_order int not null,
  is_active boolean not null,
  changed_by uuid references employees(id),
  changed_at timestamptz not null default now(),
  unique (item_id, version)
);
alter table development_item_master_versions enable row level security;

