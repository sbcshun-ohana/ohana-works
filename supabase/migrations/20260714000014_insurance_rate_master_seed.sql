--
-- 重要: 本マイグレーションの料率は以下の確度で投入している。実際の給与計算に
-- 使用する前に、必ず最新の公式資料と突き合わせて確認すること。
--
-- 【確度が高い(構造・料率とも安定)】
-- - 厚生年金保険料率 18.300%(被保険者9.150%/事業主9.150%): 2017年9月以降、
--   全国一律・料率変更なしで固定されている。等級数(32等級・標準報酬88,000円〜
--   650,000円)も2020年9月の上限拡大以降変更なし。
--
-- 【ベストエフォート(要検証): 協会けんぽは支部ごとに毎年3月分(4月納付分)から
--  改定される。以下はAI(Claude)の学習データに基づく直近水準の暫定値であり、
--  2026年度の正式な料率ではない可能性がある】
-- - 健康保険料率(協会けんぽ神奈川県支部): 9.99%と仮置き。
--   → 適用前に協会けんぽ神奈川支部の公表する最新の保険料額表で確認・修正すること。
-- - 介護保険料率(全国一律・協会けんぽ管掌分): 1.60%と仮置き。
--   → 適用前に協会けんぽの公表する最新料率で確認・修正すること。
-- - 雇用保険料率(一般の事業・被保険者負担分): 0.60%と仮置き。
--   → 適用前に厚生労働省の公表する最新の雇用保険料率で確認・修正すること
--     (雇用保険は近年頻繁に改定されており2026年度の確定値は要確認)。
--
-- 健康保険等級表(標準報酬月額との対応)は等級数(50等級)のみ構造として投入し、
-- standard_remuneration_amount(等級ごとの標準報酬月額)は本エンジンの計算では
-- 参照しない(給与計算は職員個別のstandard_monthly_remunerationsに登録された
-- 金額を用いる)ため、誤情報混入を避けて意図的にnullのままとする。
--
-- 源泉所得税額表(月額表)は国税庁公表の実テーブル(甲欄だけで100行超)であり、
-- 記憶からの手入力は転記ミスのリスクが高いため今回は投入しない。20.2章の
-- 汎用ファイル取込機能(file_import_logs)を用いた別途実装で対応する想定。

